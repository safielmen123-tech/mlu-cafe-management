const savedLang =
  typeof window !== 'undefined' ? window.localStorage.getItem(STORAGE_KEY) : null

function applyDocumentLanguage(lng) {
  if (typeof document === 'undefined') return
  const resolved = lng === 'km' ? 'km' : 'en'
  document.documentElement.lang = resolved
  if (resolved !== 'km') return
  if (document.getElementById('km-font')) return
  const link = document.createElement('link')
  link.id = 'km-font'
  link.rel = 'stylesheet'
  link.href =
    'https://fonts.googleapis.com/css2?family=Noto+Sans+Khmer:wght@400;500;600&display=swap'
  document.head.appendChild(link)
}

i18n.use(initReactI18next).init({
  resources,
  lng: savedLang === 'km' ? 'km' : 'en',
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
})

applyDocumentLanguage(i18n.language)

i18n.on('languageChanged', (lng) => {
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, lng)
  }
  applyDocumentLanguage(lng)
})

export default i18n
